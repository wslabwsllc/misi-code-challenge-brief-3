using System.Globalization;
using System.Text.Json;

namespace Dev;

/// <summary>
/// Secret scan with Gitleaks in Docker: the full Git history, then the working tree (--no-git) without generated
/// and runtime paths. A repository .gitleaks.toml is respected (extended) when present; this tool never creates it.
/// </summary>
public static class Scan
{
    // Gitleaks v8.30.1, latest stable release (GitHub releases/latest: tag v8.30.1, published 2026-03-21, not a prerelease).
    // Digest from Docker Hub tag API (hub.docker.com/v2/repositories/zricethezav/gitleaks/tags): v8.30.1 and latest
    // both resolve to this multi-arch index digest. Checked 2026-10-15.
    public const string Image = "zricethezav/gitleaks:v8.30.1@sha256:c00b6bd0aeb3071cbcb79009cb16a60dd9e0a7c60e2be9ab65d25e6bc8abbb7f";

    public static async Task<int> RunAsync()
    {
        var outDir = Repo.Path("TestResults", "gitleaks-" + DateTime.UtcNow.ToString("yyyyMMdd'T'HHmmss'Z'", CultureInfo.InvariantCulture));
        Directory.CreateDirectory(outDir);
        var repoConfig = File.Exists(Repo.Path(".gitleaks.toml"));
        // The generated config only adds path exclusions; detection rules come from the repository config if present
        // (which may itself extend the defaults), otherwise from the Gitleaks defaults.
        await File.WriteAllTextAsync(Path.Combine(outDir, "gitleaks.toml"), $$"""
            # Generated by tools/Dev scan; not committed (TestResults/ is ignored).
            title = "tools/Dev scan"

            [extend]
            {{(repoConfig ? "path = \"/repo/.gitleaks.toml\"" : "useDefault = true")}}

            [[allowlists]]
            description = "Generated, runtime and local-secret paths are not source (scanned for leaks into Git by the history pass)"
            paths = [
              '''(^|/)\.git/''',
              '''(^|/)\.data/''',
              '''(^|/)bin/''',
              '''(^|/)obj/''',
              '''(^|/)TestResults/''',
            ]
            """);
        Out.Step($"Gitleaks {Image.Split('@')[0].Split(':')[1]} (pinned by digest)");
        Out.Info(repoConfig ? "Using the repository .gitleaks.toml (extended with path exclusions)." : "No .gitleaks.toml in the repository: Gitleaks default rules.");

        var total = 0;
        var ok = true;
        foreach (var (name, extra, report) in new (string, string[], string)[]
                 {
                     ("Git history", [], "history.json"),
                     ("working tree (--no-git; excludes .data/, bin/, obj/, TestResults/)", ["--no-git"], "worktree.json"),
                 })
        {
            Out.Step($"Scan: {name}");
            var r = await Proc.RunAsync("docker",
            [
                "run", "--rm",
                "-v", $"{Repo.Root}:/repo:ro",
                "-v", $"{outDir}:/out",
                Image,
                "detect", "--source", "/repo", .. extra,
                "--config", "/out/gitleaks.toml",
                "--redact", "--no-banner", "--no-color", "--exit-code", "1",
                "--report-format", "json", "--report-path", $"/out/{report}",
            ], filter: l => !l.Contains("unable to parse remote URL", StringComparison.Ordinal) && !l.StartsWith("Unable to find image", StringComparison.Ordinal)
                            && !l.Contains("Pull", StringComparison.Ordinal) && !l.Contains("Download complete", StringComparison.Ordinal));
            var count = CountFindings(Path.Combine(outDir, report));
            if (r.ExitCode == 127) return Commands.Fail("Docker is required to run Gitleaks.");
            if (r.ExitCode is 0 or 1 && count is not null)
            {
                total += count.Value;
                if (count == 0 && r.ExitCode == 0) Out.Ok("no leaks found");
                else
                {
                    ok = false;
                    Out.Fail($"{count} finding(s) (values redacted). Report: {Path.Combine(outDir, report)}");
                    foreach (var f in Findings(Path.Combine(outDir, report))) Out.Info("  " + f);
                }
            }
            else { ok = false; Out.Fail($"Gitleaks did not complete (exit code {r.ExitCode})."); }
        }
        Out.Step(ok ? "Scan: no findings" : $"Scan: {total} finding(s) in total; reports in {outDir}");
        if (!ok) Out.Info("Fix or rotate real secrets; allowlist documented fictional values in .gitleaks.toml.");
        return ok ? 0 : 1;
    }

    /// <summary>Rule, file, line and commit of each finding. The secret itself is never read from the report.</summary>
    private static IEnumerable<string> Findings(string path)
    {
        using var doc = JsonDocument.Parse(File.ReadAllText(path));
        var lines = new List<string>();
        foreach (var f in doc.RootElement.EnumerateArray())
        {
            string S(string n) => f.TryGetProperty(n, out var v) ? v.ToString() : "";
            var commit = S("Commit");
            var file = S("File");
            if (file.StartsWith("/repo/", StringComparison.Ordinal)) file = file["/repo/".Length..];
            lines.Add($"{S("RuleID")}: {file}:{S("StartLine")}{(commit.Length >= 8 ? $" (commit {commit[..8]})" : "")}");
        }
        return lines;
    }

    private static int? CountFindings(string path)
    {
        if (!File.Exists(path)) return null;
        try
        {
            var root = JsonDocument.Parse(File.ReadAllText(path)).RootElement;
            return root.ValueKind == JsonValueKind.Array ? root.GetArrayLength() : null;
        }
        catch (JsonException)
        {
            return null;
        }
    }
}
