using System.Buffers.Binary;
using System.IO.Compression;
using System.Text;
using EventPermits.Application;

namespace EventPermits.Infrastructure.Seeding;

/// <summary>
/// Small, valid synthetic documents for the seed (E12-01 AC1): PDFs from the in-repo PDF writer, PNGs and baseline
/// JPEGs encoded here. Every file passes <see cref="FileSignatures.Validate"/>, so seeded files look exactly like uploads.
/// </summary>
public static class SyntheticFiles
{
    public static byte[] Pdf(string title, IReadOnlyList<(string Label, string Value)> fields, string body)
    {
        var pdf = new SimplePdf(title, "Memorial Event Operations (fictional practice)");
        pdf.Paragraph(title, 18, SimplePdf.Bold);
        pdf.Y += 6;
        foreach (var (label, value) in fields) pdf.Paragraph($"{label}: {value}", 11);
        pdf.Y += 8;
        pdf.Paragraph(body, 10.5);
        pdf.Y += 12;
        pdf.Paragraph("Fictional practice document generated by the seed. Not a real record.", 8.5);
        return pdf.Save();
    }

    /// <summary>An RGB PNG with a diagonal two-colour pattern (deterministic for the same arguments).</summary>
    public static byte[] Png(int width, int height, (byte R, byte G, byte B) a, (byte R, byte G, byte B) b)
    {
        using var raw = new MemoryStream();
        for (var y = 0; y < height; y++)
        {
            raw.WriteByte(0); // filter: none
            for (var x = 0; x < width; x++)
            {
                var c = ((x + y) / 8) % 2 == 0 ? a : b;
                raw.WriteByte(c.R);
                raw.WriteByte(c.G);
                raw.WriteByte(c.B);
            }
        }
        using var compressed = new MemoryStream();
        using (var z = new ZLibStream(compressed, CompressionLevel.Optimal, leaveOpen: true)) raw.WriteTo(z);

        using var png = new MemoryStream();
        png.Write([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
        var header = new byte[13];
        BinaryPrimitives.WriteInt32BigEndian(header.AsSpan(0), width);
        BinaryPrimitives.WriteInt32BigEndian(header.AsSpan(4), height);
        header[8] = 8; // bit depth
        header[9] = 2; // colour type RGB
        Chunk(png, "IHDR", header);
        Chunk(png, "IDAT", compressed.ToArray());
        Chunk(png, "IEND", []);
        return png.ToArray();
    }

    /// <summary>
    /// A minimal baseline JPEG: one 8x8 grayscale block of a uniform shade, quantisation table of ones and
    /// one-symbol Huffman tables. Real decoders open it; it is tiny and fully deterministic.
    /// </summary>
    public static byte[] Jpeg(byte shade)
    {
        // DC coefficient of a uniform block after level shift: 8 * (shade - 128); every AC coefficient is zero.
        var dc = 8 * (shade - 128);
        using var ms = new MemoryStream();
        void Marker(byte m) { ms.WriteByte(0xFF); ms.WriteByte(m); }
        void Segment(byte m, byte[] body)
        {
            Marker(m);
            ms.WriteByte((byte)((body.Length + 2) >> 8));
            ms.WriteByte((byte)((body.Length + 2) & 0xFF));
            ms.Write(body);
        }

        Marker(0xD8); // SOI
        Segment(0xE0, [.. "JFIF"u8, 0, 1, 1, 0, 0, 1, 0, 1, 0, 0]);
        // DQT: table 0, 8-bit precision, all ones.
        var dqt = new byte[65];
        for (var i = 1; i < 65; i++) dqt[i] = 1;
        Segment(0xDB, dqt);
        // SOF0: 8-bit, 8x8, one component (id 1, sampling 1x1, quant table 0).
        Segment(0xC0, [8, 0, 8, 0, 8, 1, 1, 0x11, 0]);
        // DC table 0: categories 0 and the shade's category (two codes of length 2); AC table 0: EOB only (one code of length 1).
        var category = dc == 0 ? 0 : (int)Math.Floor(Math.Log2(Math.Abs(dc))) + 1;
        var dht = new List<byte> { 0x00 };
        var dcCounts = new byte[16];
        dcCounts[1] = 2; // two codes of length 2: "00" -> category 0, "01" -> 'category'
        dht.AddRange(dcCounts);
        dht.Add(0);
        dht.Add((byte)Math.Max(category, 1));
        dht.Add(0x10);
        var acCounts = new byte[16];
        acCounts[0] = 1; // one code of length 1: "0" -> EOB
        dht.AddRange(acCounts);
        dht.Add(0x00);
        Segment(0xC4, [.. dht]);
        // SOS: one component, DC table 0 / AC table 0, full spectral range.
        Segment(0xDA, [1, 1, 0x00, 0, 63, 0]);

        var bits = new List<bool>();
        if (category == 0)
        {
            bits.AddRange([false, false]);
        }
        else
        {
            bits.AddRange([false, true]);
            var magnitude = dc > 0 ? dc : dc + (1 << category) - 1; // JPEG one's-complement style for negatives
            for (var i = category - 1; i >= 0; i--) bits.Add(((magnitude >> i) & 1) == 1);
        }
        bits.Add(false); // EOB
        while (bits.Count % 8 != 0) bits.Add(true);
        for (var i = 0; i < bits.Count; i += 8)
        {
            byte value = 0;
            for (var j = 0; j < 8; j++) value = (byte)((value << 1) | (bits[i + j] ? 1 : 0));
            ms.WriteByte(value);
            if (value == 0xFF) ms.WriteByte(0x00); // byte stuffing
        }
        Marker(0xD9); // EOI
        return ms.ToArray();
    }

    private static void Chunk(Stream png, string type, byte[] data)
    {
        Span<byte> len = stackalloc byte[4];
        BinaryPrimitives.WriteInt32BigEndian(len, data.Length);
        png.Write(len);
        var typeBytes = Encoding.ASCII.GetBytes(type);
        png.Write(typeBytes);
        png.Write(data);
        var crc = Crc32(typeBytes, data);
        BinaryPrimitives.WriteUInt32BigEndian(len, crc);
        png.Write(len);
    }

    private static readonly uint[] CrcTable = BuildCrcTable();

    private static uint[] BuildCrcTable()
    {
        var table = new uint[256];
        for (uint n = 0; n < 256; n++)
        {
            var c = n;
            for (var k = 0; k < 8; k++) c = (c & 1) != 0 ? 0xEDB88320u ^ (c >> 1) : c >> 1;
            table[n] = c;
        }
        return table;
    }

    public static uint Crc32(params byte[][] parts)
    {
        var c = 0xFFFFFFFFu;
        foreach (var part in parts)
            foreach (var b in part)
                c = CrcTable[(c ^ b) & 0xFF] ^ (c >> 8);
        return c ^ 0xFFFFFFFFu;
    }
}
